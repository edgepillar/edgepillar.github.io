import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { describeRepository, formatRepositoryDate, repositoryMetadata, selectRepositories } from "../repository-order.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const output = resolve(root, process.argv[2] || ".");
const owner = "edgepillar";
const headers = { Accept: "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28" };
if (process.env.GH_TOKEN) headers.Authorization = `Bearer ${process.env.GH_TOKEN}`;

const escape = (value) => String(value).replace(/[&<>"']/g, (character) => ({
  "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
})[character]);

async function refresh() {
  const repositories = [];
  let complete = false;
  for (let page = 1; page <= 20; page += 1) {
    const response = await fetch(`https://api.github.com/users/${owner}/repos?per_page=100&type=owner&page=${page}`, {
      headers, signal: AbortSignal.timeout(15000),
    });
    if (!response.ok) throw new Error(`GitHub API returned HTTP ${response.status}.`);
    const raw = await response.text();
    if (raw.length > 2_000_000) throw new Error("GitHub API response exceeded the size limit.");
    const pageData = JSON.parse(raw);
    if (!Array.isArray(pageData)) throw new Error("GitHub API response was not a repository list.");

    for (const item of pageData) {
      if (item.private !== false || item.owner?.login?.toLowerCase() !== owner
        || item.archived || item.disabled || item.name === "edgepillar.github.io") continue;
      if (!/^[A-Za-z0-9._-]{1,100}$/.test(item.name)
        || !Number.isSafeInteger(item.stargazers_count) || item.stargazers_count < 0
        || !Number.isFinite(Date.parse(item.pushed_at))) {
        throw new Error("GitHub API returned invalid public repository metadata.");
      }
      repositories.push({
        name: item.name,
        url: `https://github.com/${owner}/${item.name}`,
        fork: item.fork === true,
        stars: item.stargazers_count,
        pushedAt: new Date(item.pushed_at).toISOString(),
        language: typeof item.language === "string" && /^[\x20-\x7e]{1,40}$/.test(item.language) ? item.language : null,
      });
    }
    if (pageData.length < 100) { complete = true; break; }
  }
  if (!complete || repositories.length < 3) throw new Error("GitHub API repository snapshot was incomplete.");
  repositories.sort((a, b) => a.name.localeCompare(b.name, "en"));
  if (new Set(repositories.map((item) => item.name.toLowerCase())).size !== repositories.length) {
    throw new Error("GitHub API returned duplicate repositories.");
  }
  const snapshot = { updatedAt: new Date().toISOString(), repositories };
  const cards = selectRepositories(repositories).map((repository, index) => {
    const { tag, description } = describeRepository(repository);
    return `            <a class="project" href="${escape(repository.url)}" rel="noreferrer">
              <span class="project-number" aria-hidden="true">${String(index + 1).padStart(2, "0")}</span>
              <div class="project-content"><div class="project-title"><h3>${escape(repository.name)}</h3><span class="tag">${escape(tag)}</span></div><p>${escape(description)}</p><span class="project-meta">${escape(repositoryMetadata(repository))}</span></div>
              <span class="project-arrow" aria-hidden="true">↗</span>
            </a>`;
  }).join("\n");
  const html = await readFile(resolve(output, "index.html"), "utf8");
  if (!html.includes("<!-- repositories:start -->") || !html.includes("<!-- repositories:end -->")) {
    throw new Error("Repository snapshot placeholders were missing.");
  }
  const rendered = html.replace(/<!-- repositories:start -->[\s\S]*?<!-- repositories:end -->/,
    `<!-- repositories:start -->\n${cards}\n            <!-- repositories:end -->`)
    .replace(/(<span id="repository-updated">)[\s\S]*?(<\/span>)/,
      `$1Data updated ${formatRepositoryDate(snapshot.updatedAt)}$2`);
  await writeFile(resolve(output, "repositories-data.mjs"), `// Public repository metadata only. Generated by tools/refresh-repositories.mjs.\nexport const repositorySnapshot = ${JSON.stringify(snapshot, null, 2)};\n`);
  await writeFile(resolve(output, "index.html"), rendered);
  console.log(`Refreshed ${repositories.length} public repositories.`);
}

refresh().catch((error) => {
  console.error(error.message?.startsWith("GitHub API") ? error.message : "Repository refresh failed.");
  process.exitCode = 1;
});
